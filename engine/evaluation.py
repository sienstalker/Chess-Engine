def _is_endgame(board):
    """Endgame = no queens, or every side with a queen has at most one minor piece."""
    for color in (chess.WHITE, chess.BLACK):
        if board.pieces(chess.QUEEN, color):
            minors = len(board.pieces(chess.KNIGHT, color)) + len(board.pieces(chess.BISHOP, color))
            rooks = len(board.pieces(chess.ROOK, color))
            if rooks > 0 or minors > 1:
                return False
    return True


def evaluate(board):
    """Heuristic score of a non-terminal position: material + piece placement."""
    endgame = _is_endgame(board)
    score = 0
    for square, piece in board.piece_map().items():
        # Tables are drawn from White's side, so a White piece on a1 (square 0)
        # uses the bottom-left entry (index 56): flip the rank with `^ 56`.
        # Black pieces use the mirrored square, which is just `square`.
        index = square ^ 56 if piece.color == chess.WHITE else square
        if piece.piece_type == chess.KING:
            positional = (KING_END_TABLE if endgame else KING_MIDDLE_TABLE)[index]
        else:
            positional = PIECE_TABLES[piece.piece_type][index]
        value = PIECE_VALUES[piece.piece_type] + positional
        score += value if piece.color == chess.WHITE else -value
    return score
